// Optional: generate public/config.js from environment variables at build time
// (useful on Cloudflare Pages / Netlify / Vercel). Does nothing if no variables are set,
// so a hand-edited public/config.js is never overwritten by accident.
import fs from 'node:fs';
const { SUPABASE_URL, SUPABASE_ANON_KEY, ADSENSE_CLIENT, ADSENSE_SLOT_HOME, ADSENSE_SLOT_FOOTER, SITE_URL, PREMIUM_ENABLED } = process.env;
if (!SUPABASE_URL && !SUPABASE_ANON_KEY && !ADSENSE_CLIENT) { console.log('gen-config: no env vars set, keeping public/config.js'); process.exit(0); }
if (SUPABASE_ANON_KEY && /service_role/i.test(Buffer.from((SUPABASE_ANON_KEY.split('.')[1] || ''), 'base64url').toString('utf8'))) {
  console.error('gen-config: refusing to publish a service_role key. Use the anon public key.'); process.exit(1);
}
import vm from 'node:vm';
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync('public/config.js', 'utf8'), sandbox);
const base = sandbox.window.MX_CONFIG || {};
const cfg = {
  ...base,
  siteUrl: SITE_URL || base.siteUrl,
  supabaseUrl: SUPABASE_URL || '',
  supabaseAnonKey: SUPABASE_ANON_KEY || '',
  premium: { enabled: PREMIUM_ENABLED === 'true' },
  ads: { adsenseClient: ADSENSE_CLIENT || '', slots: { home: ADSENSE_SLOT_HOME || '', footer: ADSENSE_SLOT_FOOTER || '' } },
};
fs.writeFileSync('public/config.js', '/* Generated by scripts/gen-config.mjs from environment variables. Public values only. */\nwindow.MX_CONFIG = ' + JSON.stringify(cfg, null, 2) + ';\n');
console.log('gen-config: wrote public/config.js');
